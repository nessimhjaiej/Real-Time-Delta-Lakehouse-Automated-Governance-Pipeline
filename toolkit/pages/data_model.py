"""Data model page: every Delta table, its keys and relationships, checked against the data.

``collect`` reads the real schemas from MinIO (DuckDB ``delta_scan`` + the
``_delta_log`` JSON), derives key and relationship candidates from the code
(see ``_data_model_code``) and verifies each one with DuckDB
(see ``_data_model_model`` / ``_data_model_lake``). ``render`` only formats.
"""

from __future__ import annotations

from typing import Any

from toolkit.common import (
    Raw,
    badge,
    esc,
    graph_block,
    href,
    lake_connection,
    section,
    sources_html,
    stat_cards,
    table_html,
)

SLUG = "data-model"
TITLE = "Data model"
NAV_LABEL = "Data model"
BLURB = "Tables, keys and relationships from the real Delta schemas, with every key and foreign key checked against the data."
LIVE = True

LAYER_LABELS = {"bronze": "Bronze", "silver": "Silver", "gold": "Gold"}
STATUS_KIND = {"ok": "ok", "warn": "warn", "fail": "fail", "info": "info"}


def collect() -> dict[str, Any]:
    from toolkit.pages._data_model_model import build

    conn = lake_connection()
    try:
        return build(conn)
    finally:
        conn.close()


# ---------------------------------------------------------------- small helpers


def _status(status: str | None, text: str | None = None) -> Raw:
    return badge(text or (status or "n/a"), STATUS_KIND.get(status or "", "muted"))


def _table_link(table_id: str, text: str | None = None) -> Raw:
    return Raw(f'<a href="#{esc(table_id)}">{esc(text or table_id)}</a>')


def _col_ref(table_id: str, col: str) -> Raw:
    return Raw(f'{_table_link(table_id)}<span class="muted">.</span>{esc(col)}')


def _loc(text: str) -> Raw:
    return Raw(f'<code class="small">{esc(text)}</code>')


def _join(parts: list[Any], sep: str = "<br>") -> Raw:
    return Raw(sep.join(esc(p) for p in parts))


def _evidence(evidence: list[dict[str, Any]]) -> Raw:
    items = [
        f"{badge(e['kind'], 'info' if e['strength'] in ('asserted', 'declared') else 'muted')} "
        f"{esc(e['text'])} {_loc(e['loc'])}"
        for e in evidence
    ]
    return Raw("<br>".join(items))


def _pct(value: float | None) -> str:
    return "n/a" if value is None else f"{value * 100:.2f}%"


def _key_summary(
    table: dict[str, Any], keys: list[dict[str, Any]]
) -> list[dict[str, Any]]:
    return [
        k
        for k in keys
        if k["table"] == table["id"] and k["strength"] in ("asserted", "propagated")
    ]


# ---------------------------------------------------------------- sections


def _issues(data: dict[str, Any]) -> Raw:
    issues = data["issues"]
    if not issues:
        body = '<p class="muted">Every key and relationship the code asserts holds in the data.</p>'
        return section(
            "Where code intent and data disagree", body, section_id="disagreements"
        )
    rows = [
        [
            _status(i["severity"]),
            _table_link(i["subject"]),
            i["topic"],
            i["code"],
            i["data"],
        ]
        for i in issues
    ]
    body = (
        '<p class="muted small">Generated by comparing each claim the code makes '
        "(left) with a DuckDB query over the Delta table (right). "
        "Design gaps found by comparing two pieces of code (e.g. a surrogate key that "
        "omits a dedup column) are listed even when today's data happens to be clean.</p>"
        + table_html(
            ["", "Table", "Topic", "What the code says", "What the data shows"],
            rows,
            filterable=True,
            table_id="dm-issues",
        )
    )
    return section(
        "Where code intent and data disagree", body, section_id="disagreements"
    )


def _graph(data: dict[str, Any]) -> Raw:
    tables = data["tables"]
    keys = data["keys"]
    rels = data["relationships"]
    layers = list(dict.fromkeys(t["layer"] for t in tables))
    nodes: list[dict[str, Any]] = [
        {
            "id": f"layer:{layer}",
            "label": LAYER_LABELS.get(layer, layer),
            "group": layer,
        }
        for layer in layers
    ]
    for t in tables:
        types = {c["name"]: c["duckdb_type"] for c in t["columns"]}
        pk = [
            f"{'+'.join(k['columns'])} ({', '.join(types.get(c, '?') for c in k['columns'])}) — {k['status']}"
            for k in _key_summary(t, keys)
        ]
        fk_out = [
            f"{r['child_col']} ({types.get(r['child_col'], '?')}) → {r['parent']}.{r['parent_col']}"
            for r in rels
            if r["child"] == t["id"]
        ]
        nodes.append(
            {
                "id": t["id"],
                "label": t["name"],
                "group": t["layer"],
                "parent": f"layer:{t['layer']}",
                "detail": {
                    "rows": str(t["rows"]),
                    "columns": str(len(t["columns"])),
                    "keys": "; ".join(pk) or "none derived",
                    "foreign keys": "; ".join(fk_out) or "none",
                    "partition columns": ", ".join(t["partition_columns"] or [])
                    or "none",
                    "Delta version": str(t["latest_version"]),
                },
                "links": [
                    {"label": "Columns and keys (this page)", "href": f"#{t['id']}"},
                    {"label": "Catalog entry", "href": href("catalog", t["id"])},
                    {"label": "Lineage", "href": href("lineage", t["id"])},
                ],
            }
        )
    edges = []
    for r in rels:
        orphans = r["check"]["orphan_rows"] if r.get("check") else "?"
        edges.append(
            {
                "source": r["child"],
                "target": r["parent"],
                "label": f"{r['child_col']} -> {r['parent_col']} ({orphans} orphans)",
                "kind": r["strength"],
            }
        )
    graph = graph_block(
        "data-model",
        nodes,
        edges,
        groups={layer: LAYER_LABELS.get(layer, layer) for layer in layers},
        height=560,
        rank_dir="LR",
        up_label="Referenced by (child tables)",
        down_label="References (parent tables)",
    )
    node_rows = []
    for t in tables:
        pk = ", ".join("+".join(k["columns"]) for k in _key_summary(t, keys))
        node_rows.append(
            [
                _table_link(t["id"]),
                t["layer"],
                t["rows"],
                pk or "none derived",
                sum(r["child"] == t["id"] for r in rels),
                sum(r["parent"] == t["id"] for r in rels),
            ]
        )
    edge_rows = [
        [
            _col_ref(r["child"], r["child_col"]),
            _col_ref(r["parent"], r["parent_col"]),
            r["strength"],
            r["check"]["orphan_rows"] if r.get("check") else "n/a",
            _status(r["status"]),
        ]
        for r in rels
    ]
    body = (
        '<p class="muted small">One node per Delta table on MinIO, boxed by layer. '
        "An arrow points from the child table to the parent it references (foreign key); "
        "solid claims come from <code>semantic/joins.yml</code>, docstrings and SQL in the code, "
        "the rest are projected back through column lineage. Click a table to highlight what it "
        "references and what references it.</p>"
        + graph
        + "<details><summary>Graph as tables (nodes and edges)</summary>"
        + "<h3>Nodes</h3>"
        + table_html(
            ["Table", "Layer", "Rows", "Key", "FKs out", "FKs in"],
            node_rows,
            filterable=True,
            table_id="dm-nodes",
        )
        + "<h3>Edges</h3>"
        + table_html(
            ["Child column", "Parent column", "Claim", "Orphan rows", "Status"],
            edge_rows,
            filterable=True,
            table_id="dm-edges",
        )
        + "</details>"
    )
    return section("Entity-relationship graph", body, section_id="er-graph")


def _rel_rows(rels: list[dict[str, Any]]) -> list[list[Any]]:
    rows = []
    for r in rels:
        check = r.get("check") or {}
        types = " vs ".join(str(t) for t in r["types"])
        rows.append(
            [
                _col_ref(r["child"], r["child_col"]),
                _col_ref(r["parent"], r["parent_col"]),
                _evidence(r["evidence"]),
                types,
                check.get("null_fk_rows", "n/a"),
                (
                    f"{check.get('orphan_rows')} rows / {check.get('orphan_keys')} keys"
                    if check
                    else "n/a"
                ),
                _pct(check.get("match_rate")),
                (
                    f"{check.get('cardinality')}; max {check.get('max_child_rows_per_parent')} "
                    f"child rows per parent; {check.get('parents_referenced')}/{check.get('parent_keys')} "
                    "parent keys referenced"
                    if check
                    else "n/a"
                ),
                Raw(f"{_status(r['status'])} {esc(r['verdict'])}"),
            ]
        )
    return rows


REL_HEADERS = [
    "Child column",
    "Parent column",
    "Evidence in code",
    "Types (child vs parent)",
    "Null FKs",
    "Orphans",
    "Match rate",
    "Observed cardinality",
    "Verdict",
]


def _key_rows(keys: list[dict[str, Any]], with_table: bool) -> list[list[Any]]:
    rows = []
    for k in keys:
        check = k.get("check") or {}
        row: list[Any] = []
        if with_table:
            row.append(_table_link(k["table"]))
        row.extend(
            [
                ", ".join(k["columns"]),
                k["strength"],
                _evidence(k["evidence"]),
                check.get("rows", "n/a"),
                check.get("distinct", "n/a"),
                check.get("duplicate_keys", "n/a"),
                check.get("null_rows", "n/a"),
                Raw(f"{_status(k['status'])} {esc(k['verdict'])}"),
            ]
        )
        rows.append(row)
    return rows


KEY_HEADERS = [
    "Key columns",
    "Claim",
    "Evidence in code",
    "Rows",
    "Distinct keys",
    "Repeated keys",
    "Null keys",
    "Verdict",
]


def _relationships(data: dict[str, Any]) -> Raw:
    rels = data["relationships"]
    if not rels:
        return section(
            "Relationships",
            '<p class="muted">No relationship could be derived from the code.</p>',
        )
    body = (
        '<p class="muted small">Orphans: child rows whose non-null key has no parent row '
        "(left anti join). Match rate: matched / non-null child rows. Cardinality is what the "
        "data shows, not what the code says.</p>"
        + table_html(REL_HEADERS, _rel_rows(rels), filterable=True, table_id="dm-rels")
    )
    return section("Relationships", body, section_id="relationships")


def _keys(data: dict[str, Any]) -> Raw:
    body = (
        '<p class="muted small">Claim: <b>asserted</b> = the code states or enforces it '
        "(Great Expectations, dedup, surrogate key, docstring, join target); "
        "<b>propagated</b> = an asserted key that flows 1:1 into this column; "
        "<b>probe</b> = an exploratory check in a notebook; <b>pre-dedup</b> = the input of a "
        "<code>dropDuplicates</code>, where repeats are expected.</p>"
        + table_html(
            ["Table", *KEY_HEADERS],
            _key_rows(data["keys"], with_table=True),
            filterable=True,
            table_id="dm-keys",
        )
    )
    return section("Key candidates", body, section_id="keys")


def _lineage(data: dict[str, Any]) -> Raw:
    rows = []
    for e in data["lineage"]:
        derivation = badge(
            e["derivation"],
            "info" if e["derivation"] == "derived from code" else "muted",
        )
        steps = Raw(
            "<br>".join(
                f"{esc(s['kind'])}: <code>{esc(s['expr'])}</code> {_loc(s['loc'])}"
                for s in e["steps"]
            )
            or '<span class="muted">column passes through unchanged</span>'
        )
        rows.append(
            [
                _col_ref(e["from_table"], e["from_col"]),
                _col_ref(e["to_table"], e["to_col"]),
                derivation,
                steps,
                _loc(e["writer"]),
            ]
        )
    body = (
        '<p class="muted small"><b>derived from code</b>: a <code>withColumn</code>, '
        "<code>withColumnRenamed</code>, <code>select</code> or alias names the column; "
        "<b>derived by name match</b>: the writer passes every input column through and the "
        "column has the same name on both sides.</p>"
        + table_html(
            ["From", "To", "How", "Steps (expression and line)", "Written at"],
            rows,
            filterable=True,
            table_id="dm-lineage",
        )
    )
    return section("Column lineage across layers", body, section_id="column-lineage")


def _column_rows(t: dict[str, Any], data: dict[str, Any]) -> list[list[Any]]:
    lineage = data["lineage"]
    keys = [k for k in data["keys"] if k["table"] == t["id"]]
    rels = data["relationships"]
    rows = []
    for i, c in enumerate(t["columns"], start=1):
        name = c["name"]
        key_badges: list[str] = []
        for k in keys:
            if name not in k["columns"] or k["strength"] not in (
                "asserted",
                "propagated",
            ):
                continue
            label = (
                "PK"
                if len(k["columns"]) == 1
                else f"key part ({'+'.join(k['columns'])})"
            )
            kind = "pk" if k["status"] == "ok" else "fail"
            key_badges.append(
                badge(label if k["status"] == "ok" else f"{label} broken", kind)
            )
        for r in rels:
            if r["child"] == t["id"] and r["child_col"] == name:
                key_badges.append(badge(f"FK → {r['parent']}.{r['parent_col']}", "fk"))
        for rule in c["not_null_code"]:
            key_badges.append(badge(f"not null ({rule['kind']})", "info"))
        if name in (t["partition_columns"] or []):
            key_badges.append(badge("partition", "info"))
        if c.get("unique_in_data") and not any(name in k["columns"] for k in keys):
            key_badges.append(badge("unique in data, no key in code", "muted"))
        for sem in c["semantic"]:
            key_badges.append(badge(f"semantic {sem['role']}: {sem['name']}", "muted"))

        pii: list[str] = []
        hx = c.get("hex64") or {}
        if c["pii_name"] or c["pii_policy"]:
            pii.append(badge("PII", "pii"))
        if c["hashed_by"]:
            pii.append(badge("hashed in code", "ok"))
        if hx.get("rate") is not None and (
            c["pii_name"] or c["pii_policy"] or c["hashed_by"]
        ):
            hashed_pct = _pct(hx["rate"])
            pii.append(
                badge(f"{hashed_pct} SHA-256 hex", "ok" if hx["rate"] == 1 else "warn")
            )
        if c["pii_policy"]:
            pii.append(
                f'<span class="small muted">policy {esc(c["pii_policy"])}</span>'
            )

        up: list[str] = []
        for idx in c["upstream"]:
            e = lineage[idx]
            how = "code" if e["derivation"] == "derived from code" else "name match"
            kinds = ", ".join(e["kinds"]) or "pass"
            up.append(
                f"{_col_ref(e['from_table'], e['from_col'])} "
                f'<span class="small muted">[{esc(kinds)}; {esc(how)}]</span>'
            )
        if c["generated"]:
            up.append(
                f'<span class="small">generated: <code>{esc(c["generated"])}</code></span>'
            )
        if c["external"]:
            up.append(
                f'<span class="small">external source: <code>{esc(c["external"])}</code></span>'
            )
        if c.get("unexplained"):
            up.append(
                f'<span class="small muted">not derivable ({esc(", ".join(c["unexplained"]))})</span>'
            )
        if not up:
            up.append('<span class="small muted">no writer found: not derivable</span>')
        down = [
            str(_col_ref(lineage[idx]["to_table"], lineage[idx]["to_col"]))
            for idx in c["downstream"]
        ]
        delta_type = c["delta_type"] or "not in Delta log"
        nullable = (
            "n/a" if c["nullable"] is None else ("yes" if c["nullable"] else "NOT NULL")
        )
        rows.append(
            [
                i,
                Raw(f"<code>{esc(name)}</code>"),
                delta_type,
                nullable,
                c["duckdb_type"],
                Raw(" ".join(key_badges)),
                Raw(" ".join(pii)),
                c["nulls"],
                c["distinct"],
                Raw("<br>".join(up)),
                Raw("<br>".join(down) or '<span class="muted">none</span>'),
            ]
        )
    return rows


def _table_section(t: dict[str, Any], data: dict[str, Any]) -> Raw:
    if t.get("error"):
        body = f'<p>{badge("unreadable", "fail")} {esc(t["error"])}</p>'
        return section(t["id"], body, section_id=t["id"])
    op = t.get("latest_operation") or {}
    meta = [
        f"<strong>{esc(t['rows'])}</strong> rows",
        f"{esc(len(t['columns']))} columns",
        f"Delta version {esc(t['latest_version'])} ({esc(t['delta_versions'])} commits in the log)",
        f"last commit: {esc(op.get('operation'))}"
        + (f" ({esc(op.get('mode'))})" if op.get("mode") else ""),
        "partitioned by "
        + (
            esc(", ".join(t["partition_columns"]))
            if t["partition_columns"]
            else "nothing"
        ),
    ]
    if t.get("schema_matches_delta_log") is False:
        meta.append(badge("DESCRIBE differs from the Delta log schema", "warn"))
    writers = []
    for w in t["writers"]:
        reads = (
            ", ".join(str(_table_link(r)) for r in w["reads"])
            or esc(", ".join(w["external"]))
            or "nothing derivable"
        )
        writers.append(
            f"written by <code>{esc(w['function'])}</code> {_loc(w['loc'])} "
            f"(mode {esc(w['mode'] or 'default')}) from {reads}"
        )
    if not writers:
        writers.append(
            '<span class="muted">no writer found in the code (not derivable)</span>'
        )
    links = (
        f'<a href="{esc(href("catalog", t["id"]))}">catalog</a> · '
        f'<a href="{esc(href("lineage", t["id"]))}">lineage</a> · '
        f'<a href="{esc(href(SLUG, t["id"]))}">focus in graph</a>'
    )
    parts = [
        f'<p class="small">{badge(t["layer"], "info")} {links}</p>',
        f'<p class="small">{" · ".join(meta)}</p>',
        f'<p class="small">{"<br>".join(writers)}</p>',
    ]
    history = [h for h in t["schema_history"] if not h["initial"]]
    if history:
        items = "".join(
            f"<li>v{esc(h['version'])}: added {esc(', '.join(h['added']) or '—')}; "
            f"removed {esc(', '.join(h['removed']) or '—')}</li>"
            for h in history
        )
        parts.append(
            f'<details><summary>Schema changes in the Delta log ({len(history)})</summary><ul class="small">{items}</ul></details>'
        )
    tid = t["id"].replace(".", "-")
    parts.append("<h3>Columns</h3>")
    parts.append(
        table_html(
            [
                "#",
                "Column",
                "Delta type",
                "Nullable",
                "DuckDB type",
                "Keys",
                "PII",
                "Nulls",
                "Distinct",
                "Upstream",
                "Downstream",
            ],
            _column_rows(t, data),
            filterable=len(t["columns"]) > 8,
            table_id=f"dm-cols-{tid}",
        )
    )
    keys = [k for k in data["keys"] if k["table"] == t["id"]]
    parts.append("<h3>Keys</h3>")
    parts.append(
        table_html(
            KEY_HEADERS, _key_rows(keys, with_table=False), table_id=f"dm-keys-{tid}"
        )
        if keys
        else '<p class="muted small">No key candidate for this table could be derived from the code.</p>'
    )
    rels = [r for r in data["relationships"] if t["id"] in (r["child"], r["parent"])]
    parts.append("<h3>Relationships</h3>")
    parts.append(
        table_html(REL_HEADERS, _rel_rows(rels), table_id=f"dm-rels-{tid}")
        if rels
        else '<p class="muted small">No relationship touching this table could be derived.</p>'
    )
    return section(t["id"], "".join(parts), section_id=t["id"])


def _notes(data: dict[str, Any]) -> Raw:
    notes = data["notes"]
    if not notes:
        body = '<p class="muted">Every Delta column was explained by the code; nothing left over.</p>'
    else:
        body = table_html(
            ["Kind", "Note"],
            [[n["kind"], n["text"]] for n in notes],
            filterable=len(notes) > 8,
            table_id="dm-notes",
        )
    return section("Not derivable or left over", body, section_id="not-derivable")


def render(data: dict[str, Any]) -> str:
    stale = data.get("_stale_reason")
    tables = data["tables"]
    rels = data["relationships"]
    keys = [k for k in data["keys"] if k["status"] in ("ok", "fail")]
    orphan_rows = sum((r.get("check") or {}).get("orphan_rows", 0) or 0 for r in rels)
    stats = {
        "Delta tables": len(tables),
        "Columns": sum(len(t["columns"]) for t in tables),
        "Relationships": len(rels),
        "Declared in code": sum(r["strength"] == "declared" for r in rels),
        "Asserted keys holding": f"{sum(k['status'] == 'ok' for k in keys)}/{len(keys)}",
        "Orphan FK rows": orphan_rows,
        "Code vs data issues": len(data["issues"]),
    }
    toc = " · ".join(f'<a href="#{esc(t["id"])}">{esc(t["id"])}</a>' for t in tables)
    parts = [
        '<p class="lead">Generated, not drawn. Columns and types come from each Delta table on '
        "MinIO (DuckDB <code>DESCRIBE</code> on <code>delta_scan</code>, plus "
        "<code>schemaString</code> and <code>partitionColumns</code> from the <code>_delta_log</code>). "
        "Keys and relationships come from the code: Great Expectations suites, "
        "<code>dropDuplicates</code> and surrogate-key expressions found by interpreting the PySpark "
        "chains, docstrings, <code>semantic/joins.yml</code> and SQL text, each with its file and line. "
        "Each one is then checked with a DuckDB query over the data.</p>",
    ]
    if stale:
        parts.append(
            f'<p>{badge("stale", "warn")} live source failed: {esc(stale)}</p>'
        )
    parts.append(str(stat_cards(stats)))
    parts.append(f'<p class="small">Jump to a table: {toc}</p>')
    parts.append(str(_issues(data)))
    parts.append(str(_graph(data)))
    parts.append(str(_relationships(data)))
    parts.append(str(_keys(data)))
    parts.append(str(_lineage(data)))
    parts.extend(str(_table_section(t, data)) for t in tables)
    parts.append(str(_notes(data)))
    parts.append(str(sources_html(data["sources"])))
    return "".join(parts)
